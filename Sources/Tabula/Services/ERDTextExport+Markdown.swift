import Foundation

// Markdown data dictionary (GitHub-flavored).
extension ERDTextExport {

    /// Markdown data dictionary: summary, table of contents, one section per table (columns table,
    /// outgoing and incoming references) and a final relationships table. Anchors follow GitHub's
    /// heading-slug rules, including `-1`, `-2` suffixes for duplicate headings.
    static func markdownDictionary(_ g: ERDGraph) -> String {
        let p = Prepared(g)
        let title = g.title.isEmpty ? "Data dictionary" : g.title
        var slugs = MarkdownSlugger()
        _ = slugs.slug(title)
        let contentsSlug = slugs.slug("Contents")
        var anchor: [String: String] = [:]
        for t in p.tables { anchor[t.id] = slugs.slug(markdownHeading(p, t)) }
        let relationshipsSlug = p.relations.isEmpty ? "" : slugs.slug("Relationships")

        func link(_ id: String) -> String {
            guard let a = anchor[id] else { return mdText(id) }
            return "[\(mdText(p.label(id)))](#\(a))"
        }

        var out = "# \(mdText(title))\n\n"
        out += "\(p.familyName) data dictionary · \(p.summary) · generated by Tabula\n\n"

        out += "## Contents\n\n"
        for t in p.tables {
            var line = "- \(link(t.id))"
            if t.isExternal { line += " *(external)*" } else if let k = kindLabel(t.kind) { line += " *(\(k))*" }
            let c = tableComment(t)
            if !c.isEmpty { line += " — \(mdText(oneLine(c)))" }
            out += line + "\n"
        }
        if !p.relations.isEmpty { out += "- [Relationships](#\(relationshipsSlug))\n" }

        for t in p.tables {
            out += "\n## \(mdText(markdownHeading(p, t)))\n\n"
            var meta: [String] = []
            if t.isExternal { meta.append("External table, outside the exported schema; only the referenced columns are known.") }
            else if let k = kindLabel(t.kind) { meta.append("*\(k.prefix(1).uppercased() + k.dropFirst())*") }
            if p.label(t.id) != t.id && !t.isExternal { meta.append("`\(t.id)`") }
            if !meta.isEmpty { out += meta.joined(separator: " · ") + "\n\n" }
            let c = tableComment(t)
            if !c.isEmpty { out += c.components(separatedBy: .newlines).map { "> " + mdText($0) }.joined(separator: "\n") + "\n\n" }

            if t.columns.isEmpty {
                out += "*No columns.*\n"
            } else {
                out += "| Column | Type | Nullable | Key | Default | Comment |\n"
                out += "| --- | --- | :---: | :---: | --- | --- |\n"
                for col in t.columns {
                    var keys: [String] = []
                    if col.isPrimaryKey { keys.append("PK") }
                    if col.isForeignKey { keys.append("FK") }
                    if col.isUnique && !col.isPrimaryKey { keys.append("UK") }
                    let cells = [
                        mdCell(mdCode(col.name)),
                        col.type.isEmpty ? "" : mdCell(mdCode(col.type)),
                        t.isExternal ? "" : (col.nullable ? "yes" : "no"),
                        keys.joined(separator: ", "),
                        col.defaultValue.map { mdCell(mdCode($0)) } ?? "",
                        mdCell(mdText(col.comment)),
                    ]
                    out += "| " + cells.joined(separator: " | ") + " |\n"
                }
            }

            let outgoing = p.relations.filter { $0.fromTable == t.id }
            let incoming = p.relations.filter { $0.toTable == t.id }
            if !outgoing.isEmpty {
                out += "\n**References**\n\n"
                for r in outgoing {
                    out += "- \(mdColumns(r.fromColumns)) → \(link(r.toTable)) (\(mdColumns(r.toColumns))) — \(mdCode(relationLabel(r))), \(cardinality(r))\(actions(r))\n"
                }
            }
            if !incoming.isEmpty {
                out += "\n**Referenced by**\n\n"
                for r in incoming {
                    out += "- \(link(r.fromTable)) (\(mdColumns(r.fromColumns))) → \(mdColumns(r.toColumns)) — \(mdCode(relationLabel(r))), \(cardinality(r))\(actions(r))\n"
                }
            }
            out += "\n[↑ Contents](#\(contentsSlug))\n"
        }

        if !p.relations.isEmpty {
            out += "\n## Relationships\n\n"
            out += "| Name | Table | Columns | References | Columns | Cardinality | On delete | On update |\n"
            out += "| --- | --- | --- | --- | --- | --- | --- | --- |\n"
            for r in p.relations {
                let cells = [
                    mdCell(mdCode(relationLabel(r))), mdCell(link(r.fromTable)), mdCell(mdColumns(r.fromColumns)),
                    mdCell(link(r.toTable)), mdCell(mdColumns(r.toColumns)), cardinality(r),
                    mdCell(mdText(r.onDelete)), mdCell(mdText(r.onUpdate)),
                ]
                out += "| " + cells.joined(separator: " | ") + " |\n"
            }
        }
        return out
    }

    private static func markdownHeading(_ p: Prepared, _ t: ERDTable) -> String {
        p.label(t.id)
    }

    private static func cardinality(_ r: ERDRelation) -> String {
        (r.oneToOne ? "one-to-one" : "many-to-one") + (r.optional ? " (optional)" : "")
    }

    private static func actions(_ r: ERDRelation) -> String {
        var parts: [String] = []
        if !r.onDelete.isEmpty && r.onDelete.uppercased() != "NO ACTION" { parts.append("on delete \(r.onDelete)") }
        if !r.onUpdate.isEmpty && r.onUpdate.uppercased() != "NO ACTION" { parts.append("on update \(r.onUpdate)") }
        return parts.isEmpty ? "" : ", " + parts.joined(separator: ", ")
    }

    private static func mdColumns(_ cols: [String]) -> String {
        cols.map(mdCode).joined(separator: ", ")
    }

    /// Inline code span that survives backticks in the content.
    static func mdCode(_ s: String) -> String {
        let v = oneLine(s)
        if v.isEmpty { return "" }
        guard v.contains("`") else { return "`\(v)`" }
        var fence = "``"
        while v.contains(fence) { fence += "`" }
        return "\(fence) \(v) \(fence)"
    }

    /// Plain text with Markdown/HTML syntax characters escaped.
    static func mdText(_ s: String) -> String {
        let chars = Array(s)
        var out = ""
        for (i, ch) in chars.enumerated() {
            switch ch {
            case "\\", "`", "*", "[", "]", "<", ">", "|", "#": out += "\\\(ch)"
            case "_":
                // GFM never treats intraword underscores as emphasis (snake_case stays readable).
                let intraword = i > 0 && i + 1 < chars.count && (chars[i - 1].isLetter || chars[i - 1].isNumber)
                    && (chars[i + 1].isLetter || chars[i + 1].isNumber || chars[i + 1] == "_")
                out += intraword ? "_" : "\\_"
            default: out.append(ch)
            }
        }
        return out
    }

    /// Table cell: no line breaks, `|` escaped (also inside code spans, as GFM requires).
    static func mdCell(_ s: String) -> String {
        var out = ""
        var prev: Character = " "
        for ch in s.replacingOccurrences(of: "\r\n", with: "\n") {
            if ch == "\n" || ch == "\r" { out += "<br>"; prev = " "; continue }
            if ch == "|" && prev != "\\" { out += "\\|" } else { out.append(ch) }
            prev = ch
        }
        return out
    }
}

/// GitHub heading anchors (github-slugger): lowercase, drop punctuation except `-`/`_`, spaces → `-`,
/// repeated slugs get `-1`, `-2`… suffixes in document order.
struct MarkdownSlugger {
    private var seen: [String: Int] = [:]

    mutating func slug(_ heading: String) -> String {
        var base = ""
        for u in heading.lowercased().unicodeScalars {
            let p = u.properties
            if u == " " { base += "-" }
            else if u == "-" || u == "_" || p.isAlphabetic || p.numericType != nil || p.generalCategory == .nonspacingMark || p.generalCategory == .spacingMark {
                base.unicodeScalars.append(u)
            }
        }
        var s = base
        if let n = seen[base] {
            var k = n
            repeat { k += 1; s = "\(base)-\(k)" } while seen[s] != nil
            seen[base] = k
        } else {
            seen[base] = 0
        }
        seen[s] = seen[s] ?? 0
        return s
    }
}
