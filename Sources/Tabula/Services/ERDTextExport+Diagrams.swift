import Foundation

// PlantUML and Graphviz DOT exporters (layout is left to the respective tools).
extension ERDTextExport {

    // MARK: - PlantUML

    /// PlantUML entity-relationship diagram in IE (crow's foot) notation.
    /// Mandatory (NOT NULL) columns are prefixed with `*`, key columns sit above a `--` separator.
    static func plantUML(_ g: ERDGraph) -> String {
        let p = Prepared(g)
        let aliases = uniqueAliases(p.tables.map(\.id), label: { p.label($0) }, prefix: "t_")
        var out = "@startuml\n"
        if !g.title.isEmpty { out += "title \(plantUMLText(g.title))\n" }
        out += "' \(p.familyName): \(p.summary). Generated by Tabula.\n"
        out += "hide circle\nhide empty members\nskinparam linetype ortho\nskinparam shadowing false\nskinparam roundCorner 4\n"
        out += "skinparam class {\n  BackgroundColor #FFFFFF\n  BorderColor #5B6573\n  HeaderBackgroundColor #E6ECF3\n  ArrowColor #5B6573\n}\n"
        for t in p.tables {
            var header = "entity \"\(plantUMLText(p.label(t.id)))\" as \(aliases[t.id]!)"
            if t.isExternal { header += " <<external>> #line.dashed" }
            else if let k = kindLabel(t.kind) { header += " <<\(k)>> #line.dashed" }
            out += "\n\(header) {\n"
            let keys = t.columns.filter(\.isPrimaryKey)
            let rest = t.columns.filter { !$0.isPrimaryKey }
            for c in keys { out += "  \(plantUMLMember(c))\n" }
            if !keys.isEmpty && !rest.isEmpty { out += "  --\n" }
            for c in rest { out += "  \(plantUMLMember(c))\n" }
            out += "}\n"
        }
        if !p.relations.isEmpty { out += "\n" }
        for r in p.relations {
            let parentSide = r.optional ? "|o" : "||"
            let childSide = r.oneToOne ? "o|" : "o{"
            out += "\(aliases[r.toTable]!) \(parentSide)--\(childSide) \(aliases[r.fromTable]!) : \(plantUMLText(relationLabel(r)))\n"
        }
        out += "@enduml\n"
        return out
    }

    private static func plantUMLMember(_ c: ERDColumn) -> String {
        var s = (c.nullable ? "" : "* ") + plantUMLText(c.name, member: true)
        if !c.type.isEmpty { s += " : " + plantUMLText(c.type) }
        var tags: [String] = []
        if c.isPrimaryKey { tags.append("<<PK>>") }
        if c.isForeignKey { tags.append("<<FK>>") }
        if c.isUnique && !c.isPrimaryKey { tags.append("<<UK>>") }
        if !tags.isEmpty { s += " " + tags.joined(separator: " ") }
        return s
    }

    /// Single-line text with PlantUML/Creole syntax neutralized via numeric character references:
    /// HTML-ish tags, quotes, `{static}`-style modifiers, `~` escapes, Creole pairs (`**`, `//`, `__`, `--`, `""`,
    /// `[[`…) and, at the start of a member, visibility markers (`-`, `#`, `+`, `~`, `*`).
    static func plantUMLText(_ s: String, member: Bool = false) -> String {
        let chars = Array(oneLine(s))
        var out = ""
        for (i, ch) in chars.enumerated() {
            let next: Character? = i + 1 < chars.count ? chars[i + 1] : nil
            var encode = false
            switch ch {
            case "\"", "<", ">", "{", "}", "~", "&": encode = true
            case "*", "/", "_", "-", "=", "[", "]", ".", "'": encode = next == ch
            default: break
            }
            if member && i == 0 && "-#+~*'".contains(ch) { encode = true }  // `'` would start a comment
            if encode, let v = ch.unicodeScalars.first?.value { out += "&#\(v);" } else { out.append(ch) }
        }
        return out
    }

    /// Stable, unique `[A-Za-z0-9_]` aliases derived from the display labels.
    static func uniqueAliases(_ ids: [String], label: (String) -> String, prefix: String) -> [String: String] {
        var used: Set<String> = []
        var out: [String: String] = [:]
        for id in ids {
            var base = String(label(id).unicodeScalars.map { isASCIIWord($0) ? Character($0) : "_" })
            if base.isEmpty || base.first!.isNumber { base = prefix + base }
            var a = base
            var n = 2
            while used.contains(a.lowercased()) { a = "\(base)_\(n)"; n += 1 }
            used.insert(a.lowercased())
            out[id] = a
        }
        return out
    }

    // MARK: - Graphviz DOT

    /// Graphviz DOT with HTML-like table labels. Every column row has ports (`cN_l` on the left cell,
    /// `cN_r` on the right cell) so edges attach to the actual FK/PK rows; arrowheads use crow's foot shapes.
    static func dot(_ g: ERDGraph) -> String {
        let p = Prepared(g)
        var out = "// \(oneLine(g.title)) (\(p.familyName)): \(p.summary). Generated by Tabula.\n"
        out += "digraph ERD {\n"
        out += "  graph [rankdir=LR, splines=spline, nodesep=0.5, ranksep=1.0, pad=0.3, bgcolor=\"white\", fontname=\"Helvetica\", fontsize=16"
        if !g.title.isEmpty { out += ", labelloc=t, label=\(dotString(g.title))" }
        out += "];\n"
        out += "  node [shape=plaintext, margin=0, fontname=\"Helvetica\", fontsize=11];\n"
        out += "  edge [color=\"#5B6573\", penwidth=1.2, arrowsize=0.9, dir=both, fontname=\"Helvetica\", fontsize=9];\n"
        for t in p.tables {
            out += "\n  \(dotString(t.id)) [tooltip=\(dotString(tooltip(for: t))), label=<\(dotTableLabel(t, title: p.label(t.id)))>];\n"
        }
        if !p.relations.isEmpty { out += "\n" }
        for r in p.relations {
            guard let child = p.byID[r.fromTable], let parent = p.byID[r.toTable] else { continue }
            let from = dotEndpoint(child, column: r.fromColumns.first, side: "r", compass: "e")
            let to = dotEndpoint(parent, column: r.toColumns.first, side: "l", compass: "w")
            let tail = r.oneToOne ? "teeodot" : "crowodot"     // child side
            let head = r.optional ? "teeodot" : "teetee"        // parent side
            var attrs = ["arrowtail=\(tail)", "arrowhead=\(head)"]
            var tip = "\(relationLabel(r)): \(child.name)(\(r.fromColumns.joined(separator: ", "))) → \(parent.name)(\(r.toColumns.joined(separator: ", ")))"
            if !r.onDelete.isEmpty && r.onDelete.uppercased() != "NO ACTION" { tip += ", on delete \(r.onDelete)" }
            attrs.append("tooltip=\(dotString(tip))")
            if child.isExternal || parent.isExternal { attrs.append("style=dashed") }
            out += "  \(from) -> \(to) [\(attrs.joined(separator: ", "))];\n"
        }
        out += "}\n"
        return out
    }

    private static func tooltip(for t: ERDTable) -> String {
        var s = t.id
        if t.isExternal { s += " (external)" } else if let k = kindLabel(t.kind) { s += " (\(k))" }
        let c = tableComment(t)
        if !c.isEmpty { s += ": " + c }
        return s
    }

    private static func dotEndpoint(_ t: ERDTable, column: String?, side: String, compass: String) -> String {
        guard let column, let i = t.columns.firstIndex(where: { $0.name == column }) else { return dotString(t.id) }
        return "\(dotString(t.id)):\"c\(i)_\(side)\":\(compass)"
    }

    private static func dotTableLabel(_ t: ERDTable, title: String) -> String {
        let special = t.isExternal || t.kind != .table
        let headerBG = special ? "#ECEEF1" : "#DCE6F2"
        var tableAttrs = "BORDER=\"1\" CELLBORDER=\"0\" CELLSPACING=\"0\" CELLPADDING=\"4\" COLOR=\"#5B6573\""
        if special { tableAttrs += " STYLE=\"dashed\"" }
        var s = "<TABLE \(tableAttrs)>"
        var head = "<B>\(html(title))</B>"
        if t.isExternal { head += "<BR/><FONT POINT-SIZE=\"9\" COLOR=\"#6B7280\">external</FONT>" }
        else if let k = kindLabel(t.kind) { head += "<BR/><FONT POINT-SIZE=\"9\" COLOR=\"#6B7280\">\(k)</FONT>" }
        s += "<TR><TD COLSPAN=\"3\" BGCOLOR=\"\(headerBG)\" ALIGN=\"CENTER\">\(head)</TD></TR>"
        for (i, c) in t.columns.enumerated() {
            var name = c.name.isEmpty ? " " : html(c.name)
            if c.isPrimaryKey { name = "<B>\(name)</B>" }
            if c.isForeignKey && !c.isPrimaryKey { name = "<I>\(name)</I>" }
            var keys: [String] = []
            if c.isPrimaryKey { keys.append("PK") }
            if c.isForeignKey { keys.append("FK") }
            if c.isUnique && !c.isPrimaryKey { keys.append("UK") }
            let type = html(c.type)
            let tip = c.comment.isEmpty ? "" : " TOOLTIP=\"\(html(oneLine(c.comment)))\""
            s += "<TR>"
            s += "<TD PORT=\"c\(i)_l\" ALIGN=\"LEFT\"\(tip)>\(name)</TD>"
            s += "<TD ALIGN=\"LEFT\">\(font(type, "COLOR=\"#6B7280\""))</TD>"
            s += "<TD PORT=\"c\(i)_r\" ALIGN=\"RIGHT\">\(font(keys.joined(separator: " "), "COLOR=\"#8A6D1F\" POINT-SIZE=\"9\""))</TD>"
            s += "</TR>"
        }
        if t.columns.isEmpty { s += "<TR><TD COLSPAN=\"3\"> </TD></TR>" }
        return s + "</TABLE>"
    }

    /// `<FONT>` wrapper; Graphviz rejects the whole label when a FONT element is empty.
    private static func font(_ text: String, _ attrs: String) -> String {
        text.isEmpty ? "" : "<FONT \(attrs)>\(text)</FONT>"
    }

    /// Escapes text for Graphviz HTML-like labels.
    static func html(_ s: String) -> String {
        var out = ""
        for ch in s {
            switch ch {
            case "&": out += "&amp;"
            case "<": out += "&lt;"
            case ">": out += "&gt;"
            case "\"": out += "&quot;"
            case "\n", "\r", "\r\n": out += " "
            default: out.append(ch)
            }
        }
        return out
    }

    /// Double-quoted DOT ID / string.
    static func dotString(_ s: String) -> String {
        "\"" + oneLine(s).replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
