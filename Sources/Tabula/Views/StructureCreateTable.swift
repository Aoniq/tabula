import SwiftUI
import AppKit

// MARK: - Model + SQL generation

struct NewTableColumn: Identifiable, Hashable {
    let id = UUID()
    var name: String
    var type: String
    var nullable = true
    var defaultValue = ""
    var primaryKey = false
    var autoIncrement = false
}

enum CreateTableSQL {
    /// The starting `id` column, using each engine's auto-increment idiom.
    static func idColumn(_ family: DatabaseFamily) -> NewTableColumn {
        NewTableColumn(name: "id", type: family == .sqlite ? "INTEGER" : "bigint", nullable: false, primaryKey: true, autoIncrement: true)
    }

    static func defaultType(_ family: DatabaseFamily) -> String {
        switch family {
        case .postgres: return "text"
        case .mysql: return "varchar(255)"
        default: return "TEXT"
        }
    }

    static func isIntegerType(_ type: String) -> Bool {
        let t = type.lowercased().trimmingCharacters(in: .whitespaces)
        return ["int", "integer", "bigint", "smallint", "mediumint", "tinyint", "int2", "int4", "int8", "serial", "bigserial", "smallserial"]
            .contains { t == $0 || t.hasPrefix($0 + "(") || t.hasPrefix($0 + " ") }
    }

    /// Builds the CREATE TABLE statement (plus COMMENT ON TABLE for Postgres) for the sheet's current state.
    static func generate(family: DatabaseFamily, schema: String?, table: String, columns: [NewTableColumn], comment: String) throws -> String {
        let d = SQLDialect(family: family)
        let name = table.trimmingCharacters(in: .whitespaces)
        guard !name.isEmpty else { throw DBError("Enter a table name") }
        let obj = DBObject(schema: family == .postgres ? schema : nil, name: name, kind: .table)
        let q = d.qualified(obj)

        let cols = columns.filter { !$0.name.trimmingCharacters(in: .whitespaces).isEmpty }
        guard !cols.isEmpty else { throw DBError("Add at least one column") }
        var seen = Set<String>()
        for c in cols {
            let n = c.name.trimmingCharacters(in: .whitespaces)
            if !seen.insert(n.lowercased()).inserted { throw DBError("Duplicate column name “\(n)”") }
            if c.type.trimmingCharacters(in: .whitespaces).isEmpty { throw DBError("Column “\(n)” needs a type") }
        }
        let pk = cols.filter(\.primaryKey)
        let auto = cols.filter(\.autoIncrement)

        var sqliteInlinePK = false
        switch family {
        case .sqlite:
            if let a = auto.first {
                guard auto.count == 1, pk.count == 1, pk[0].id == a.id, a.type.trimmingCharacters(in: .whitespaces).uppercased() == "INTEGER" else {
                    throw DBError("SQLite AUTOINCREMENT needs a single INTEGER PRIMARY KEY column")
                }
                sqliteInlinePK = true
            }
        case .mysql:
            if auto.count > 1 { throw DBError("MySQL allows only one AUTO_INCREMENT column") }
            if let a = auto.first, !a.primaryKey { throw DBError("The AUTO_INCREMENT column “\(a.name)” must be part of the primary key") }
        default:
            break
        }
        for a in auto where !isIntegerType(a.type) {
            throw DBError("Auto-increment column “\(a.name)” needs an integer type")
        }

        var lines: [String] = cols.map { c in
            let n = d.quoteIdent(c.name.trimmingCharacters(in: .whitespaces))
            let type = c.type.trimmingCharacters(in: .whitespaces)
            let def = c.defaultValue.trimmingCharacters(in: .whitespaces)
            var l = "  \(n) "
            if c.autoIncrement {
                switch family {
                case .postgres:
                    l += type.lowercased().contains("serial") ? type : "\(type) GENERATED BY DEFAULT AS IDENTITY"
                    if c.primaryKey || !c.nullable { l += " NOT NULL" }
                case .mysql:
                    l += "\(type) NOT NULL AUTO_INCREMENT"
                default:
                    l += "INTEGER PRIMARY KEY AUTOINCREMENT"
                }
                return l
            }
            l += type
            if c.primaryKey || !c.nullable { l += " NOT NULL" }
            if !def.isEmpty { l += " DEFAULT \(family == .mysql ? StructureDraft.mysqlDefault(def) : def)" }
            return l
        }
        if !pk.isEmpty && !sqliteInlinePK {
            lines.append("  PRIMARY KEY (\(pk.map { d.quoteIdent($0.name.trimmingCharacters(in: .whitespaces)) }.joined(separator: ", ")))")
        }
        var sql = "CREATE TABLE \(q) (\n\(lines.joined(separator: ",\n"))\n)"
        let note = comment.trimmingCharacters(in: .whitespacesAndNewlines)
        if family == .mysql && !note.isEmpty { sql += " COMMENT = \(d.literal(note))" }
        sql += ";"
        if family == .postgres && !note.isEmpty { sql += "\nCOMMENT ON TABLE \(q) IS \(d.literal(note));" }
        return sql
    }
}

// MARK: - Sheet

struct CreateTableSheet: View {
    let ws: WorkspaceState
    @Environment(\.dismiss) private var dismiss

    @State private var name = ""
    @State private var schema = ""
    @State private var comment = ""
    @State private var columns: [NewTableColumn] = []
    @State private var running = false
    @State private var runError: String?
    @FocusState private var focus: Field?

    private enum Field: Hashable { case name, column(UUID) }

    private var family: DatabaseFamily { ws.family }
    private var types: [String] { ws.dialect.commonTypes }

    private var generated: Result<String, Error> {
        Result { try CreateTableSQL.generate(family: family, schema: schema.isEmpty ? nil : schema, table: name, columns: columns, comment: comment) }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            Text("Create Table").font(.headline).padding([.horizontal, .top], 16).padding(.bottom, 10)

            Grid(alignment: .leading, horizontalSpacing: 10, verticalSpacing: 8) {
                GridRow {
                    Text("Name").foregroundStyle(.secondary).gridColumnAlignment(.trailing)
                    HStack {
                        TextField("table_name", text: $name).textFieldStyle(.roundedBorder).focused($focus, equals: .name)
                        if family == .postgres {
                            Text("Schema").foregroundStyle(.secondary)
                            Picker("", selection: $schema) {
                                ForEach(schemaOptions, id: \.self) { Text($0).tag($0) }
                            }
                            .labelsHidden().frame(width: 160)
                        }
                    }
                }
                if family == .postgres || family == .mysql {
                    GridRow {
                        Text("Comment").foregroundStyle(.secondary)
                        TextField("Optional", text: $comment).textFieldStyle(.roundedBorder)
                    }
                }
            }
            .padding(.horizontal, 16)
            .padding(.bottom, 12)

            columnGrid
                .padding(.horizontal, 16)

            HStack {
                Button { addColumn() } label: { Label("Column", systemImage: "plus") }
                Spacer()
                Text("Default is a raw SQL expression, e.g. 0, 'text', now()").font(.caption).foregroundStyle(.secondary)
            }
            .controlSize(.small)
            .padding(.horizontal, 16).padding(.vertical, 8)

            Text("SQL Preview").font(.caption.weight(.semibold)).foregroundStyle(.secondary).padding(.horizontal, 16)
            ScrollView {
                Group {
                    switch generated {
                    case .success(let sql): Text(sql).foregroundStyle(.primary)
                    case .failure(let e): Text(e.localizedDescription).foregroundStyle(.orange)
                    }
                }
                .font(.system(.callout, design: .monospaced))
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(8)
            }
            .frame(height: 150)
            .background(Color(nsColor: .textBackgroundColor))
            .overlay(RoundedRectangle(cornerRadius: 6).stroke(Color(nsColor: .separatorColor)))
            .clipShape(RoundedRectangle(cornerRadius: 6))
            .padding(.horizontal, 16).padding(.top, 4)

            if let runError {
                Label(runError, systemImage: "exclamationmark.triangle.fill")
                    .foregroundStyle(.red).font(.callout).textSelection(.enabled)
                    .padding(.horizontal, 16).padding(.top, 8)
            }

            Spacer(minLength: 12)
            Divider()
            HStack {
                if running { ProgressView().controlSize(.small) }
                Spacer()
                Button("Cancel") { dismiss() }.keyboardShortcut(.cancelAction)
                Button("Create") { create() }
                    .keyboardShortcut(.return, modifiers: .command)
                    .buttonStyle(.borderedProminent)
                    .disabled(running || (try? generated.get()) == nil)
                    .help("Create table (⌘↩)")
            }
            .padding(12)
        }
        .frame(width: 820, height: 640)
        .onAppear {
            if columns.isEmpty {
                columns = [CreateTableSQL.idColumn(family)]
                schema = ws.currentSchema ?? (ws.schemas.first ?? "public")
            }
            focus = .name
        }
    }

    private var schemaOptions: [String] {
        var s = ws.schemas
        if !schema.isEmpty && !s.contains(schema) { s.insert(schema, at: 0) }
        return s
    }

    // MARK: Column grid

    private struct Spec { let title: String; let width: CGFloat?; var minWidth: CGFloat = 60; var center = false }

    /// Flexible columns resolved to fixed widths (sheet is 820 wide, 16pt margins) so rows line up.
    private var specs: [Spec] {
        let total: CGFloat = 820 - 32 - 2
        let fixed = baseSpecs.compactMap(\.width).reduce(0, +)
        let flexMin = baseSpecs.filter { $0.width == nil }.map(\.minWidth).reduce(0, +)
        let extra = max(0, total - fixed - flexMin)
        return baseSpecs.map { s in
            s.width != nil ? s : Spec(title: s.title, width: (s.minWidth + extra * s.minWidth / flexMin).rounded(.down), minWidth: s.minWidth, center: s.center)
        }
    }

    private var baseSpecs: [Spec] {
        [Spec(title: "", width: 44),
         Spec(title: "Name", width: nil, minWidth: 140),
         Spec(title: "Type", width: nil, minWidth: 170),
         Spec(title: "Nullable", width: 60, center: true),
         Spec(title: "Default", width: nil, minWidth: 120),
         Spec(title: "Primary", width: 56, center: true),
         Spec(title: "Auto Inc.", width: 60, center: true),
         Spec(title: "", width: 30, center: true)]
    }

    private var columnGrid: some View {
        VStack(spacing: 0) {
            HStack(spacing: 0) {
                ForEach(Array(specs.enumerated()), id: \.offset) { _, s in
                    Text(s.title).font(.caption.weight(.semibold)).foregroundStyle(.secondary).lineLimit(1).gridCell(s.width, s.minWidth, s.center)
                }
            }
            .background(Color(nsColor: .controlBackgroundColor))
            Divider()
            ScrollView {
                VStack(spacing: 0) {
                    ForEach(Array(columns.enumerated()), id: \.element.id) { i, c in
                        row(i, c)
                            .background(i % 2 == 1 ? Color(nsColor: .alternatingContentBackgroundColors[1]) : Color.clear)
                        Divider().opacity(0.5)
                    }
                }
            }
        }
        .frame(height: 210)
        .overlay(RoundedRectangle(cornerRadius: 6).stroke(Color(nsColor: .separatorColor)))
        .clipShape(RoundedRectangle(cornerRadius: 6))
    }

    private func row(_ i: Int, _ c: NewTableColumn) -> some View {
        let s = specs
        return HStack(spacing: 0) {
            HStack(spacing: 0) {
                Button { move(i, -1) } label: { Image(systemName: "chevron.up") }.disabled(i == 0)
                Button { move(i, 1) } label: { Image(systemName: "chevron.down") }.disabled(i == columns.count - 1)
            }
            .buttonStyle(.borderless).controlSize(.mini)
            .gridCell(s[0].width, s[0].minWidth, true)

            TextField("column_name", text: bind(c.id, \.name, ""))
                .textFieldStyle(.plain).focused($focus, equals: .column(c.id))
                .gridCell(s[1].width, s[1].minWidth, false)

            HStack(spacing: 2) {
                TextField("type", text: bind(c.id, \.type, "")).textFieldStyle(.plain).font(.system(.body, design: .monospaced))
                Menu {
                    ForEach(types, id: \.self) { t in Button(t) { update(c.id) { $0.type = t } } }
                } label: { Image(systemName: "chevron.down") }
                    .menuStyle(.borderlessButton).menuIndicator(.hidden).fixedSize()
            }
            .gridCell(s[2].width, s[2].minWidth, false)

            Toggle("", isOn: bind(c.id, \.nullable, true)).toggleStyle(.checkbox).labelsHidden()
                .disabled(c.primaryKey)
                .gridCell(s[3].width, s[3].minWidth, true)

            TextField(c.autoIncrement ? "auto" : "NULL", text: bind(c.id, \.defaultValue, ""))
                .textFieldStyle(.plain).font(.system(.body, design: .monospaced)).disabled(c.autoIncrement)
                .gridCell(s[4].width, s[4].minWidth, false)

            Toggle("", isOn: Binding(get: { c.primaryKey }, set: { v in
                update(c.id) { $0.primaryKey = v; if v { $0.nullable = false } else { $0.autoIncrement = $0.autoIncrement && family == .postgres } }
            }))
            .toggleStyle(.checkbox).labelsHidden()
            .gridCell(s[5].width, s[5].minWidth, true)

            Toggle("", isOn: Binding(get: { c.autoIncrement }, set: { v in setAutoIncrement(c.id, v) }))
                .toggleStyle(.checkbox).labelsHidden()
                .gridCell(s[6].width, s[6].minWidth, true)

            Button { columns.removeAll { $0.id == c.id } } label: { Image(systemName: "minus.circle") }
                .buttonStyle(.borderless).help("Remove column")
                .gridCell(s[7].width, s[7].minWidth, true)
        }
        .frame(maxWidth: .infinity, minHeight: 26, maxHeight: 26, alignment: .leading)
    }

    private func bind<V>(_ id: UUID, _ kp: WritableKeyPath<NewTableColumn, V>, _ fallback: V) -> Binding<V> {
        Binding(get: { columns.first { $0.id == id }?[keyPath: kp] ?? fallback },
                set: { v in update(id) { $0[keyPath: kp] = v } })
    }

    private func update(_ id: UUID, _ body: (inout NewTableColumn) -> Void) {
        guard let i = columns.firstIndex(where: { $0.id == id }) else { return }
        body(&columns[i])
    }

    private func setAutoIncrement(_ id: UUID, _ on: Bool) {
        update(id) { c in
            c.autoIncrement = on
            guard on else { return }
            c.defaultValue = ""
            c.nullable = false
            c.primaryKey = true
            if family == .sqlite { c.type = "INTEGER" }
            else if !CreateTableSQL.isIntegerType(c.type) { c.type = "bigint" }
        }
        // Engines other than Postgres allow a single auto-increment column.
        if on && family != .postgres {
            for i in columns.indices where columns[i].id != id { columns[i].autoIncrement = false }
        }
    }

    private func move(_ i: Int, _ delta: Int) {
        let j = i + delta
        guard columns.indices.contains(i), columns.indices.contains(j) else { return }
        columns.swapAt(i, j)
    }

    private func addColumn() {
        let c = NewTableColumn(name: "", type: CreateTableSQL.defaultType(family))
        columns.append(c)
        DispatchQueue.main.async { focus = .column(c.id) }
    }

    private func create() {
        guard case .success(let sql) = generated else { return }
        let tableName = name.trimmingCharacters(in: .whitespaces)
        let targetSchema = family == .postgres ? schema : nil
        let toastBefore = ws.toast?.id
        running = true
        runError = nil
        Task {
            await ws.runAdminStatement(sql, success: "Created table \(tableName)")
            running = false
            guard let t = ws.toast, t.id != toastBefore else { return }   // cancelled by safe mode
            if t.isError {
                runError = t.message
                return
            }
            let obj = ws.objects.first { $0.kind == .table && $0.name == tableName && (targetSchema == nil || $0.schema == targetSchema) }
                ?? DBObject(schema: targetSchema, name: tableName, kind: .table)
            dismiss()
            ws.openTable(obj)
        }
    }
}

private extension View {
    func gridCell(_ width: CGFloat?, _ minWidth: CGFloat, _ center: Bool) -> some View {
        self.padding(.horizontal, 6)
            .frame(minWidth: width ?? minWidth, maxWidth: width ?? .infinity, minHeight: 24, alignment: center ? .center : .leading)
            .overlay(alignment: .trailing) { Rectangle().fill(Color(nsColor: .separatorColor).opacity(0.6)).frame(width: 1) }
    }
}
